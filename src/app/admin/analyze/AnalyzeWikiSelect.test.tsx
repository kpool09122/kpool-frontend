import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { AnalyzeWikiSelect } from "./AnalyzeWikiSelect";
const search = vi.hoisted(() => vi.fn());
vi.mock("@/gateways/wiki/translationSetMasterSearchBrowserApi", () => ({ fetchAllTranslationSetMasterSearch: search }));
const item = { translationSetIdentifier: "11111111-1111-4111-8111-111111111111", displayWiki: { name: "TWICE", slug: "gr-twice" } };
afterEach(() => { cleanup(); vi.resetAllMocks(); });
const show = () => render(<QueryClientProvider client={new QueryClient()}><form><AnalyzeWikiSelect label="Wiki" disabled={false} /></form><button>Outside</button></QueryClientProvider>);
it("supports keyboard results, Escape dismissal, selection and clearing without a second selected-name row", async () => {
  search.mockResolvedValue({ translationSetMasters: [item] });
  const { container } = show();
  const input = screen.getByRole("combobox", { name: "Wiki" });
  fireEvent.change(input, { target: { value: "twice" } });
  fireEvent.keyDown(input, { key: "Enter" });
  const option = await screen.findByRole("option", { name: "TWICE gr-twice" });
  fireEvent.keyDown(input, { key: "ArrowDown" });
  expect(option).toHaveFocus();
  fireEvent.keyDown(option, { key: "Escape" });
  expect(input).toHaveFocus();
  expect(input).toHaveAttribute("aria-expanded", "false");
  expect(screen.queryByRole("listbox")).not.toBeInTheDocument();
  fireEvent.keyDown(input, { key: "Enter" });
  fireEvent.click(await screen.findByRole("option", { name: "TWICE gr-twice" }));
  expect(input).toHaveValue("TWICE");
  expect(container.querySelector('input[name="target"]')).toHaveValue(item.translationSetIdentifier);
  expect(screen.queryByText("TWICE")).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "削除: TWICE" }));
  expect(input).toHaveValue("");
  expect(container.querySelector('input[name="target"]')).toHaveValue("");
});
it("cancels an obsolete search and does not reopen its results after typing", async () => {
  let complete: (value: unknown) => void = () => {};
  search.mockImplementation(() => new Promise((resolve) => { complete = resolve; }));
  show();
  const input = screen.getByRole("combobox", { name: "Wiki" });
  fireEvent.change(input, { target: { value: "old" } });
  fireEvent.keyDown(input, { key: "Enter" });
  const signal = search.mock.calls[0][0].signal as AbortSignal;
  fireEvent.change(input, { target: { value: "new" } });
  expect(signal.aborted).toBe(true);
  await act(async () => complete({ translationSetMasters: [item] }));
  expect(input).toHaveValue("new");
  expect(screen.queryByRole("listbox")).not.toBeInTheDocument();
});
